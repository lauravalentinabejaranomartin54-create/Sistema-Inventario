    // Muestra la vista de login o de registro
    private void mostrarVista(String vista) {
        CardLayout tarjetas = (CardLayout) pnlTarjeta.getLayout();
        tarjetas.show(pnlTarjeta, vista);
        boolean esLogin = VISTA_LOGIN.equals(vista);
        // La tecla Enter activa el botón principal de la vista actual
        getRootPane().setDefaultButton(esLogin ? btnIngresar : btnRegistrar);
        setTitle(esLogin ? "Inventario - Iniciar sesión" : "Inventario - Crear cuenta");
        if (esLogin) {
            txtUsuario.requestFocusInWindow();
        } else {
            txtNuevoUsuario.requestFocusInWindow();
        }
    }

