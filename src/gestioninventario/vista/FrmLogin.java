    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        try {
            Usuario usuario = controlador.iniciarSesion(txtUsuario.getText(), txtContrasena.getPassword());
            // Abrimos el menú y cerramos el login
            new FrmMenu(usuario).setVisible(true);
            dispose();
        } catch (IllegalArgumentException e) {
            txtContrasena.setText("");
            Mensajes.advertencia(this, e.getMessage());
        } catch (SQLException e) {
            Mensajes.errorBaseDatos(this, e);
        }
    }//GEN-LAST:event_btnIngresarActionPerformed

